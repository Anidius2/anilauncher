export const dictionaries = { ru, en };

export function translate(lang: "ru" | "en", key: Key, vars?: Record<string, string | number>): string {
  let s = (dictionaries[lang] ?? ru)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
